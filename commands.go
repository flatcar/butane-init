package transpile

import (
	"fmt"
	"strings"

	base "github.com/coreos/ignition/v2/butane/base/v0_5"
	"github.com/goccy/go-yaml/ast"
)

const (
	// Not /etc: Flatcar mounts /etc as a noexec confext overlay.
	commandsDir   = "/opt/butane-init"
	commandsBin   = commandsDir + "/bin"
	commandsState = "/var/lib/butane-init"
	semDir        = commandsState + "/sem"
)

// commandReservedPaths are owned by the generated command units, even when a
// config does not use them, so write_files cannot interfere with them.
var commandReservedPaths = []string{
	commandsDir,
	commandsState,
	"/etc/systemd/system/butane-init-bootcmd.service",
	"/etc/systemd/system/butane-init-bootcmd.service.d",
	"/etc/systemd/system/butane-init-runcmd.service",
	"/etc/systemd/system/butane-init-runcmd.service.d",
	// Ignition appends enablement presets here; systemd then creates the
	// wants symlinks. Either can be blocked or overridden by a written file.
	"/etc/systemd/system-preset/20-ignition.preset",
	"/etc/systemd/system/multi-user.target.wants/butane-init-bootcmd.service",
	"/etc/systemd/system/multi-user.target.wants/butane-init-runcmd.service",
}

// The environment is scoped to the generated units. /opt/bin is where Flatcar
// installations commonly place kubeadm; the cloud-init-per replacement comes first.
const commandsEnvironment = `Environment=PATH=` + commandsBin + `:/opt/bin:/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin
Environment=HOME=/root
Environment=INSTANCE_ID=%m
`

// bootcmd runs on every boot, like cloud-init's init stage: after basic
// networking and before network-online.target and runcmd. Its failure is
// logged without blocking runcmd.
const bootcmdUnit = `[Unit]
Description=Butane Init cloud-config bootcmd
After=network.target
Before=network-online.target butane-init-runcmd.service

[Service]
Type=oneshot
RemainAfterExit=yes
` + commandsEnvironment + `ExecStart=` + commandsDir + `/bootcmd.sh

[Install]
WantedBy=multi-user.target
`

// runcmd runs once per instance (machine ID). Like cloud-init's semaphore, the
// marker is written before the commands run, so failed or interrupted
// commands are not retried on reboot.
const runcmdUnit = `[Unit]
Description=Butane Init cloud-config runcmd
Wants=network-online.target
After=network-online.target butane-init-bootcmd.service
ConditionPathExists=!` + semDir + `/%m/runcmd

[Service]
Type=oneshot
RemainAfterExit=yes
` + commandsEnvironment + `ExecStartPre=/usr/bin/mkdir -p ` + semDir + `/%m
ExecStartPre=/usr/bin/touch ` + semDir + `/%m/runcmd
ExecStart=` + commandsDir + `/runcmd.sh

[Install]
WantedBy=multi-user.target
`

// cloudInitPer replaces cloud-init's tools/cloud-init-per, which Flatcar does
// not ship. "instance" markers are stored per machine ID.
const cloudInitPer = `#!/bin/sh
# Generated by Butane Init as a replacement for cloud-init's cloud-init-per.
usage() {
    echo "Usage: ${0##*/} once|instance|always name cmd [arg ...]"
}
fail() {
    echo "$@" 1>&2
    exit 1
}
if [ "$1" = "-h" ] || [ "$1" = "--help" ]; then
    usage
    exit 0
fi
[ $# -ge 3 ] || { usage 1>&2; exit 1; }
freq=$1
name=$(printf '%s' "$2" | sed 's/-/_/g')
shift 2
[ "${name#*/}" = "$name" ] || fail "name cannot contain a /"
[ "$(id -u)" = "0" ] || fail "must be root"
case "$freq" in
    once | always) sem="` + semDir + `/bootper.$name.$freq" ;;
    instance) sem="` + semDir + `/$(cat /etc/machine-id)/bootper.$name.$freq" ;;
    *)
        usage 1>&2
        fail "invalid frequency: $freq"
        ;;
esac
mkdir -p "${sem%/*}" || fail "failed to make directory for $sem"
[ "$freq" != "always" ] && [ -e "$sem" ] && exit 0
"$@"
ret=$?
printf '%s\t%s\n' "$ret" "$(date +%s)" > "$sem" || fail "failed to write to $sem"
exit $ret
`

// parseCommands converts bootcmd and runcmd into scripts and oneshot units.
func parseCommands(document map[string]any, file *ast.File) ([]base.File, []base.Unit, ValidationErrors) {
	var files []base.File
	var units []base.Unit
	var problems ValidationErrors
	for _, stanza := range []struct{ key, unit string }{
		{"bootcmd", bootcmdUnit},
		{"runcmd", runcmdUnit},
	} {
		raw, exists := document[stanza.key]
		if !exists {
			continue
		}
		items, ok := raw.([]any)
		if !ok {
			problems = append(problems, problem(file, stanza.key, "must be a list"))
			continue
		}
		// Like cloud-init: one line per command, without set -e.
		var script strings.Builder
		script.WriteString("#!/bin/sh\n")
		for i, item := range items {
			command, ok := item.(string)
			if !ok {
				message := "must be a string"
				if _, isList := item.([]any); isList {
					message = "must be a string; argument lists are unsupported"
				}
				problems = append(problems, problem(file, fmt.Sprintf("%s[%d]", stanza.key, i), message))
				continue
			}
			script.WriteString(command + "\n")
		}
		if len(items) == 0 {
			continue
		}
		// Commands can embed bootstrap tokens, so only root may read them.
		files = append(files, commandFile(commandsDir+"/"+stanza.key+".sh", script.String(), 0o700))
		enabled := true
		contents := stanza.unit
		units = append(units, base.Unit{Name: "butane-init-" + stanza.key + ".service", Enabled: &enabled, Contents: &contents})
	}
	if len(problems) > 0 {
		return nil, nil, problems
	}
	if len(units) > 0 {
		files = append(files, commandFile(commandsBin+"/cloud-init-per", cloudInitPer, 0o755))
	}
	return files, units, nil
}

func commandFile(path, contents string, mode int) base.File {
	file := generatedFile(path, contents)
	file.Mode = &mode
	return file
}
